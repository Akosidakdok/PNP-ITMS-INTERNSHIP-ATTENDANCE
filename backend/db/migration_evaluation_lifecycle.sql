-- Evaluation lifecycle controls: archive/restore metadata and safe filtering.
-- This migration is safe to run even when the base schema was not imported
-- first. Existing evaluation rows and columns are preserved.
CREATE TABLE IF NOT EXISTS public.evaluations (
  id bigint generated by default as identity primary key,
  intern_id bigint not null,
  evaluator_id bigint not null,
  evaluator_name text not null,
  evaluation_date timestamptz not null default now(),
  overall_score numeric not null,
  overall_rating text not null,
  comments text,
  work_quality numeric,
  punctuality numeric,
  teamwork numeric,
  communication numeric,
  initiative numeric,
  archived_at timestamptz,
  archived_by bigint REFERENCES public.accounts(id) ON DELETE SET NULL,
  archive_reason text,
  created_at timestamptz not null default now()
);

ALTER TABLE public.evaluations
  ADD COLUMN IF NOT EXISTS archived_at timestamptz,
  ADD COLUMN IF NOT EXISTS archived_by bigint REFERENCES public.accounts(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS archive_reason text;

CREATE INDEX IF NOT EXISTS idx_evaluations_archived_at
  ON public.evaluations(archived_at, evaluation_date DESC);

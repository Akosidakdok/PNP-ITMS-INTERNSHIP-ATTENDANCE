import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('combined Supabase deployment installs all attendance updates and can be rerun safely', async () => {
  const db = new PGlite();
  try {
    await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
      CREATE SCHEMA auth;
      CREATE FUNCTION auth.email() RETURNS text LANGUAGE sql AS $$ SELECT NULL::text $$;
      CREATE TABLE accounts (id bigint PRIMARY KEY, full_name text, email text, role text);
      CREATE TABLE attendance_logs (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        intern_id bigint, intern_name text, scan_type text, scan_time timestamptz, approval_status text);
      INSERT INTO accounts VALUES (7,'Controlled Intern','controlled@test.invalid','intern'),
        (8,'Normal Intern','normal@test.invalid','intern'),(9,'Approver','approver@test.invalid','superadmin');`);
    const sql = await readFile(new URL('../db/deploy_controlled_attendance.sql', import.meta.url), 'utf8');
    await db.exec(sql);
    await db.exec(`INSERT INTO account_attendance_profiles (account_id,attendance_profile_id,assigned_by)
        SELECT 7,id,9 FROM attendance_profiles ORDER BY id LIMIT 1;
      INSERT INTO attendance_logs (id,intern_id,scan_type,scan_time,actual_scan_time,recorded_scan_time,attendance_profile_id)
        SELECT 1,7,'time_in','2026-10-29T09:20:51+08'::timestamptz,'2026-10-29T09:20:51+08'::timestamptz,
          '2026-10-29T08:00+08'::timestamptz,id FROM attendance_profiles ORDER BY id LIMIT 1;
      INSERT INTO attendance_logs (id,intern_id,scan_type,scan_time,actual_scan_time,recorded_scan_time)
        VALUES (2,8,'time_in','2026-10-29T09:20:51+08','2026-10-29T09:20:51+08','2026-10-29T09:20:51+08');`);
    const { rows: before } = await db.query('SELECT * FROM attendance_scan_audit ORDER BY id');
    await db.exec(sql);
    const { rows: after } = await db.query('SELECT * FROM attendance_scan_audit ORDER BY id');
    assert.deepEqual(after, before, 'rerunning must not duplicate or change audit evidence');
    const { rows } = await db.query('SELECT * FROM attendance_logs ORDER BY id');
    assert.ok(rows[0].actual_scan_time.getTime() >= new Date('2026-10-29T07:45:00+08:00').getTime());
    assert.ok(rows[0].actual_scan_time.getTime() <= new Date('2026-10-29T08:00:00+08:00').getTime());
    assert.equal(rows[0].scan_adjustment_rule, 'randomized_time_in_v2');
    assert.equal(rows[0].original_scan_time.toISOString(), '2026-10-29T01:20:51.000Z');
    assert.equal(rows[1].actual_scan_time.toISOString(), '2026-10-29T01:20:51.000Z');
    assert.equal(rows[1].superadmin_controlled, false);
    const { rows: [count] } = await db.query('SELECT count(*)::int AS total FROM accounts');
    assert.equal(count.total, 3, 'deployment must not create default administrator accounts');
  } finally { await db.close(); }
});

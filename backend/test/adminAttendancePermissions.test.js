import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

process.env.SUPABASE_URL ||= 'http://admin-permissions.test';
process.env.SUPABASE_SERVICE_ROLE_KEY ||= 'test-key';
process.env.JWT_SECRET ||= 'admin-permissions-test-secret';
const { adminOnlyMiddleware } = await import('../src/middleware.js');

test('the requested APIs allow Admin and Superadmin while rejecting other roles', async () => {
  const source = await readFile(new URL('../src/index.js', import.meta.url), 'utf8');
  const routes = [
    ['get', '/admin/accounts'], ['post', '/admin/accounts'],
    ['put', '/admin/dtr/:internId/edit'],
    ['get', '/admin/dtr/:internId/history'], ['get', '/admin/dtr-history'],
    ['get', '/admin/attendance-control/profiles'], ['post', '/admin/attendance-control/profiles'],
    ['put', '/admin/attendance-control/profiles/:id'],
    ['patch', '/admin/attendance-control/profiles/:id/status'],
    ['get', '/admin/attendance-control/accounts'],
    ['post', '/admin/attendance-control/assignments'],
    ['delete', '/admin/attendance-control/assignments/:accountId'],
    ['post', '/admin/attendance-control/individual/:accountId'],
  ];
  for (const [method, route] of routes) {
    assert.ok(source.includes(`app.${method}('${route}', authMiddleware, adminOnlyMiddleware,`), `${method} ${route}`);
  }
  for (const role of ['admin', 'superadmin', 'supervisor', 'intern', null]) {
    let allowed = false;
    let status;
    const res = { status(value) { status = value; return this; }, json() {} };
    adminOnlyMiddleware({ user: role ? { id: 10, role } : null }, res, () => { allowed = true; });
    assert.equal(allowed, ['admin', 'superadmin'].includes(role), String(role));
    if (!allowed) assert.equal(status, 403);
  }
  for (const [method, route] of [['patch', '/auth/username'], ['post', '/attendance/:attendanceId/image'],
    ['put', '/attendance/:attendanceId/image'], ['delete', '/attendance/:attendanceId/image']]) {
    assert.ok(source.includes(`app.${method}('${route}', authMiddleware, superadminMiddleware,`), `unrelated restriction: ${route}`);
  }
});

test('Admin attendance control and protected DTR corrections preserve PostgreSQL audit guarantees', async t => {
  const db = new PGlite();
  try {
    await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
      CREATE SCHEMA auth;
      CREATE FUNCTION auth.email() RETURNS text LANGUAGE sql AS $$ SELECT NULL::text $$;
      CREATE TABLE accounts (id bigint PRIMARY KEY, full_name text, email text, role text);
      CREATE TABLE attendance_logs (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        intern_id bigint, intern_name text, scan_type text, scan_time timestamptz, approval_status text);
      INSERT INTO accounts VALUES (7,'Intern','intern@test.invalid','intern'),
        (9,'Superadmin','super@test.invalid','superadmin'),(10,'Demo Admin','admin@test.invalid','admin'),
        (11,'Supervisor','supervisor@test.invalid','supervisor');`);
    const deployment = await readFile(new URL('../db/deploy_controlled_attendance.sql', import.meta.url), 'utf8');
    await db.exec(deployment);
    await db.exec(`GRANT USAGE ON SCHEMA public TO service_role;
      GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO service_role;
      GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
      INSERT INTO account_attendance_profiles (account_id,attendance_profile_id,assigned_by)
        SELECT 7,id,10 FROM attendance_profiles ORDER BY id LIMIT 1;
      INSERT INTO attendance_logs (id,intern_id,scan_type,scan_time,actual_scan_time,recorded_scan_time,attendance_profile_id)
        SELECT 100,7,'time_in','2026-10-29T09:20:51+08'::timestamptz,'2026-10-29T09:20:51+08'::timestamptz,
          '2026-10-29T08:00+08'::timestamptz,id FROM attendance_profiles ORDER BY id LIMIT 1;
      INSERT INTO attendance_records (account_id,attendance_date,actual_time_in,recorded_time_in,status)
        VALUES (7,'2026-10-29','2026-10-29T01:20:51Z','2026-10-29T00:00Z','pending');`);

    const correct = async (actor = 10, reason = 'Verified attendance correction') => {
      await db.exec('SET ROLE service_role');
      try {
        return await db.query(`SELECT public.apply_controlled_dtr_edit($1,$2,$3::jsonb,$4::jsonb,$5::jsonb,$6::jsonb,$7::jsonb,$8)`,
          [7, 1, JSON.stringify([{ id: 100, changes: { recorded_scan_time: '2026-10-29T00:05Z',
            adjustment_mode: 'manual', adjustment_reason: reason } }]), '[]',
          JSON.stringify({ recorded_time_in: '2026-10-29T00:05Z', status: 'pending' }), '{}',
          JSON.stringify([{ field_name: 'Time In', original_value: '08:00 AM', new_value: '08:05 AM', reason }]), actor]);
      } finally { await db.exec('RESET ROLE'); }
    };

    await t.test('Admin-assigned profiles create protected scans with the actual approving role', async () => {
      const { rows: [scan] } = await db.query('SELECT * FROM attendance_logs WHERE id=100');
      assert.equal(scan.superadmin_controlled, true);
      assert.equal(scan.original_scan_time.toISOString(), '2026-10-29T01:20:51.000Z');
      const { rows: [audit] } = await db.query('SELECT * FROM attendance_scan_audit WHERE attendance_log_id=100 ORDER BY id LIMIT 1');
      assert.equal(audit.approved_by, 10);
      assert.equal(audit.policy_snapshot.approved_by_role, 'admin');
      assert.equal(audit.policy_snapshot.approved_by_name, 'Demo Admin');
    });

    await t.test('Supervisor, Intern, missing actors, and empty reasons cannot correct protected records', async () => {
      for (const actor of [11, 7, 999, null]) await assert.rejects(correct(actor), /admin.*approval/i);
      await assert.rejects(correct(10, '  '), /reason/i);
    });

    await t.test('failed audit insertion rolls back the scan, mirror, and edit history', async () => {
      await db.exec(`CREATE FUNCTION fail_admin_audit() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN RAISE EXCEPTION 'audit unavailable'; END $$;
        CREATE TRIGGER fail_admin_audit BEFORE INSERT ON attendance_scan_audit
        FOR EACH ROW EXECUTE FUNCTION fail_admin_audit();`);
      await assert.rejects(correct(), /audit unavailable/);
      assert.equal((await db.query('SELECT recorded_time_in FROM attendance_records WHERE id=1')).rows[0].recorded_time_in.toISOString(), '2026-10-29T00:00:00.000Z');
      assert.equal((await db.query('SELECT recorded_scan_time FROM attendance_logs WHERE id=100')).rows[0].recorded_scan_time.toISOString(), '2026-10-29T00:00:00.000Z');
      assert.equal((await db.query('SELECT count(*)::int AS count FROM dtr_edit_history')).rows[0].count, 0);
      await db.exec('DROP TRIGGER fail_admin_audit ON attendance_scan_audit');
    });

    await t.test('Admin can save the protected correction after unassignment without changing actual scans or approval status', async () => {
      await db.exec('DELETE FROM account_attendance_profiles WHERE account_id=7');
      await correct();
      const { rows: [record] } = await db.query('SELECT * FROM attendance_records WHERE id=1');
      assert.equal(record.recorded_time_in.toISOString(), '2026-10-29T00:05:00.000Z');
      assert.equal(record.actual_time_in.toISOString(), '2026-10-29T01:20:51.000Z');
      assert.equal(record.status, 'pending');
      const { rows: [audit] } = await db.query('SELECT * FROM attendance_scan_audit WHERE attendance_log_id=100 ORDER BY id DESC LIMIT 1');
      assert.equal(audit.actual_scan_time.toISOString(), '2026-10-29T01:20:51.000Z');
      assert.equal(audit.approved_by, 10);
      assert.equal(audit.policy_snapshot.approved_by_role, 'admin');
      assert.equal((await db.query('SELECT modified_by FROM dtr_edit_history')).rows[0].modified_by, 10);
      await correct(9);
    });

    await t.test('original QR evidence and audit rows remain immutable and RPC stays private', async () => {
      await assert.rejects(db.exec("UPDATE attendance_logs SET original_scan_time=now() WHERE id=100"), /immutable/i);
      await assert.rejects(db.exec("UPDATE attendance_scan_audit SET reason='rewrite'"), /immutable/i);
      await assert.rejects(db.exec('DELETE FROM attendance_scan_audit'), /immutable/i);
      const { rows: [grants] } = await db.query(`SELECT
        has_function_privilege('anon','public.apply_controlled_dtr_edit(bigint,bigint,jsonb,jsonb,jsonb,jsonb,jsonb,bigint)','EXECUTE') AS anon,
        has_function_privilege('authenticated','public.apply_controlled_dtr_edit(bigint,bigint,jsonb,jsonb,jsonb,jsonb,jsonb,bigint)','EXECUTE') AS authenticated`);
      assert.deepEqual(grants, { anon: false, authenticated: false });
    });
  } finally { await db.close(); }
});

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('administrators delete protected attendance while retaining immutable evidence', async t => {
  const db = new PGlite();
  try {
    await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
      CREATE SCHEMA auth;
      CREATE FUNCTION auth.email() RETURNS text LANGUAGE sql AS $$ SELECT NULL::text $$;
      CREATE TABLE accounts (id bigint PRIMARY KEY, full_name text, email text, role text);
      CREATE TABLE attendance_logs (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        intern_id bigint, intern_name text, scan_type text, scan_time timestamptz, approval_status text, remarks text);
      CREATE TABLE attendance_photos (attendance_log_id bigint REFERENCES attendance_logs(id), photo text);
      INSERT INTO accounts VALUES (7,'Intern','intern@test.invalid','intern'),
        (9,'Superadmin','super@test.invalid','superadmin'),(10,'Admin','admin@test.invalid','admin'),
        (11,'Supervisor','supervisor@test.invalid','supervisor');`);
    const deployment = await readFile(new URL('../db/deploy_controlled_attendance.sql', import.meta.url), 'utf8');
    await db.exec(deployment.split('-- Individual administrator attendance deletion, retaining immutable QR evidence.')[0]);
    await db.exec(await readFile(new URL('../../supabase/migrations/20261029060918_admin_attendance_deletion.sql', import.meta.url), 'utf8'));
    await db.exec(`GRANT USAGE ON SCHEMA public TO service_role;
      GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO service_role;
      GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
      INSERT INTO account_attendance_profiles (account_id,attendance_profile_id,assigned_by)
        SELECT 7,id,9 FROM attendance_profiles ORDER BY id LIMIT 1;
      INSERT INTO attendance_records (id,account_id,attendance_date,actual_time_in,recorded_time_in,status)
        OVERRIDING SYSTEM VALUE VALUES (30,7,(now() AT TIME ZONE 'Asia/Manila')::date,
          date_trunc('day',now() AT TIME ZONE 'Asia/Manila') AT TIME ZONE 'Asia/Manila' + interval '9 hours',
          date_trunc('day',now() AT TIME ZONE 'Asia/Manila') AT TIME ZONE 'Asia/Manila' + interval '8 hours','approved');`);

    const insertScan = async (id, status = 'approved', hour = 9) => {
      await db.query(`INSERT INTO attendance_logs
          (id,intern_id,scan_type,scan_time,actual_scan_time,recorded_scan_time,attendance_profile_id,attendance_record_id,approval_status)
        SELECT $1,7,'time_in',
          ((now() AT TIME ZONE 'Asia/Manila')::date + make_time($3,0,0)) AT TIME ZONE 'Asia/Manila',
          ((now() AT TIME ZONE 'Asia/Manila')::date + make_time($3,0,0)) AT TIME ZONE 'Asia/Manila',
          ((now() AT TIME ZONE 'Asia/Manila')::date + TIME '08:00') AT TIME ZONE 'Asia/Manila',
          id,30,$2 FROM attendance_profiles ORDER BY id LIMIT 1`, [id, status, hour]);
      await db.query('INSERT INTO attendance_photos VALUES ($1,$2)', [id, 'selfie']);
    };
    const remove = async (id, actor, rescan = false) => {
      await db.exec('SET ROLE service_role');
      try {
        return await db.query('SELECT public.delete_admin_attendance_entry($1,$2,$3) AS result', [id, actor, rescan]);
      } finally { await db.exec('RESET ROLE'); }
    };

    await t.test('admin deletion removes the entry and selfie, clears its daily mirror and keeps evidence', async () => {
      await insertScan(1);
      const { rows: before } = await db.query('SELECT * FROM attendance_scan_audit WHERE attendance_log_id=1 ORDER BY id');
      const { rows: [{ result }] } = await remove(1, 10);
      assert.equal(result.removed.id, 1);
      assert.equal(result.audit_preserved, true);
      assert.deepEqual((await db.query('SELECT * FROM attendance_logs WHERE id=1')).rows, []);
      assert.deepEqual((await db.query('SELECT * FROM attendance_photos WHERE attendance_log_id=1')).rows, []);
      const { rows: audits } = await db.query('SELECT * FROM attendance_scan_audit WHERE attendance_log_id=1 ORDER BY id');
      assert.deepEqual(audits.slice(0, -1), before);
      const deletion = audits.at(-1);
      assert.equal(deletion.event_type, 'attendance_deleted');
      assert.equal(deletion.approved_by, 10);
      assert.equal(deletion.actual_scan_time.toISOString(), before[0].actual_scan_time.toISOString());
      assert.match(deletion.reason, /administrator/i);
      const { rows: [mirror] } = await db.query('SELECT actual_time_in,recorded_time_in FROM attendance_records WHERE id=30');
      assert.equal(mirror.actual_time_in, null);
      assert.equal(mirror.recorded_time_in, null);
      await assert.rejects(db.exec("UPDATE attendance_scan_audit SET reason='rewrite'"), /immutable|protected/i);
    });

    await t.test('superadmins can delete protected scans after control unassignment', async () => {
      await insertScan(2);
      await db.exec('DELETE FROM account_attendance_profiles WHERE account_id=7');
      assert.equal((await remove(2, 9)).rows[0].result.removed.id, 2);
      await db.exec(`INSERT INTO account_attendance_profiles (account_id,attendance_profile_id,assigned_by)
        SELECT 7,id,9 FROM attendance_profiles ORDER BY id LIMIT 1`);
    });

    await t.test('interns, supervisors and missing actors cannot use protected deletion', async () => {
      await insertScan(3);
      for (const actor of [7, 11, 999, null]) {
        await assert.rejects(remove(3, actor), /admin/i);
      }
      assert.equal((await db.query('SELECT id FROM attendance_logs WHERE id=3')).rows.length, 1);
      assert.equal((await db.query("SELECT id FROM attendance_scan_audit WHERE attendance_log_id=3 AND event_type='attendance_deleted'")).rows.length, 0);
      await assert.rejects(db.exec('DELETE FROM attendance_logs WHERE id=3'), /protected/i);
      await assert.rejects(db.exec("UPDATE attendance_logs SET original_scan_time=now() WHERE id=3"), /immutable/i);
    });

    await t.test('failed audit storage rolls back deletion and selfie cleanup', async () => {
      await db.exec(`CREATE FUNCTION reject_deletion_audit() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN IF NEW.event_type='attendance_deleted' THEN RAISE EXCEPTION 'audit unavailable'; END IF; RETURN NEW; END $$;
        CREATE TRIGGER reject_deletion_audit BEFORE INSERT ON attendance_scan_audit
        FOR EACH ROW EXECUTE FUNCTION reject_deletion_audit();`);
      await assert.rejects(remove(3, 10), /audit unavailable/);
      assert.equal((await db.query('SELECT id FROM attendance_logs WHERE id=3')).rows.length, 1);
      assert.equal((await db.query('SELECT photo FROM attendance_photos WHERE attendance_log_id=3')).rows[0].photo, 'selfie');
      await db.exec('DROP TRIGGER reject_deletion_audit ON attendance_scan_audit');
    });

    await t.test('a delete failure rolls back its audit event and photo deletion', async () => {
      const { rows: before } = await db.query('SELECT * FROM attendance_scan_audit WHERE attendance_log_id=3 ORDER BY id');
      await db.exec(`CREATE FUNCTION reject_attendance_delete() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN RAISE EXCEPTION 'delete unavailable'; END $$;
        CREATE TRIGGER zz_reject_attendance_delete BEFORE DELETE ON attendance_logs
        FOR EACH ROW EXECUTE FUNCTION reject_attendance_delete();`);
      await assert.rejects(remove(3, 10), /delete unavailable/);
      assert.deepEqual((await db.query('SELECT * FROM attendance_scan_audit WHERE attendance_log_id=3 ORDER BY id')).rows, before);
      assert.equal((await db.query('SELECT photo FROM attendance_photos WHERE attendance_log_id=3')).rows[0].photo, 'selfie');
      await db.exec('DROP TRIGGER zz_reject_attendance_delete ON attendance_logs');
    });

    await t.test('rescan removal still requires today’s latest rejected scan', async () => {
      await assert.rejects(remove(3, 10, true), /rejected/i);
      await insertScan(4, 'rejected', 10);
      await insertScan(5, 'rejected', 11);
      await assert.rejects(remove(4, 10, true), /latest/i);
      assert.equal((await remove(5, 10, true)).rows[0].result.removed.id, 5);
      const { rows: [remaining] } = await db.query('SELECT original_scan_time,actual_scan_time,recorded_scan_time FROM attendance_logs WHERE id=3');
      const { rows: [mirror] } = await db.query('SELECT actual_time_in,recorded_time_in FROM attendance_records WHERE id=30');
      assert.equal(mirror.actual_time_in.toISOString(), remaining.original_scan_time.toISOString());
      assert.equal(mirror.recorded_time_in.toISOString(), remaining.recorded_scan_time.toISOString());
      await db.exec(`INSERT INTO attendance_logs (id,intern_id,scan_type,scan_time,actual_scan_time,recorded_scan_time,approval_status)
        VALUES (6,7,'time_in',now()-interval '2 days',now()-interval '2 days',now()-interval '2 days','rejected')`);
      await assert.rejects(remove(6, 10, true), /today/i);
    });

    await t.test('deleting an afternoon entry preserves the real morning QR instant in the mirror', async () => {
      const { rows: [morning] } = await db.query('SELECT original_scan_time FROM attendance_logs WHERE id=3');
      await db.exec(`UPDATE attendance_records SET actual_time_in=(SELECT original_scan_time FROM attendance_logs WHERE id=3) WHERE id=30;
        INSERT INTO attendance_logs (id,intern_id,scan_type,scan_time,actual_scan_time,recorded_scan_time,attendance_profile_id,attendance_record_id,approval_status)
          SELECT 8,7,'time_out', ((now() AT TIME ZONE 'Asia/Manila')::date + TIME '17:00') AT TIME ZONE 'Asia/Manila',
            ((now() AT TIME ZONE 'Asia/Manila')::date + TIME '17:00') AT TIME ZONE 'Asia/Manila',
            ((now() AT TIME ZONE 'Asia/Manila')::date + TIME '17:00') AT TIME ZONE 'Asia/Manila',id,30,'approved'
          FROM attendance_profiles ORDER BY id LIMIT 1;`);
      await remove(8, 10);
      const { rows: [mirror] } = await db.query('SELECT actual_time_in,actual_time_out FROM attendance_records WHERE id=30');
      assert.equal(mirror.actual_time_in.toISOString(), morning.original_scan_time.toISOString());
      assert.equal(mirror.actual_time_out, null);
    });

    await t.test('RPC is unavailable to client database roles and does not leave deletion authorization enabled', async () => {
      const { rows: [privileges] } = await db.query(`SELECT
        has_function_privilege('anon','public.delete_admin_attendance_entry(bigint,bigint,boolean)','EXECUTE') AS anon,
        has_function_privilege('authenticated','public.delete_admin_attendance_entry(bigint,bigint,boolean)','EXECUTE') AS authenticated`);
      assert.deepEqual(privileges, { anon: false, authenticated: false });
      await db.exec('SET ROLE service_role');
      try { await assert.rejects(db.exec('DELETE FROM attendance_logs WHERE id=3'), /protected/i); }
      finally { await db.exec('RESET ROLE'); }
      await assert.rejects(remove(999, 10), /not found/i);
    });
  } finally { await db.close(); }
});

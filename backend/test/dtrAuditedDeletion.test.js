import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('DTR deletion removes protected dates atomically while retaining original QR evidence', async t => {
  const db = new PGlite();
  try {
    await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
      CREATE SCHEMA auth;
      CREATE FUNCTION auth.email() RETURNS text LANGUAGE sql AS $$ SELECT NULL::text $$;
      CREATE TABLE accounts (id bigint PRIMARY KEY, full_name text, email text, role text);
      CREATE TABLE attendance_logs (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        intern_id bigint, intern_name text, scan_type text, scan_time timestamptz, approval_status text, remarks text);
      CREATE TABLE attendance_photos (attendance_log_id bigint REFERENCES attendance_logs(id), photo text);
      INSERT INTO accounts VALUES (7,'Intern','intern@test.invalid','intern'),(8,'Other Intern','other@test.invalid','intern'),
        (9,'Superadmin','super@test.invalid','superadmin'),(10,'Demo Admin','admin@test.invalid','admin'),
        (11,'Supervisor','supervisor@test.invalid','supervisor');`);
    await db.exec(await readFile(new URL('../db/deploy_controlled_attendance.sql', import.meta.url), 'utf8'));
    const migration = await readFile(new URL('../../supabase/migrations/20261030104116_dtr_audited_deletion.sql', import.meta.url), 'utf8');
    await db.exec(migration);
    await db.exec(`GRANT USAGE ON SCHEMA public TO service_role;
      GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO service_role;
      GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
      INSERT INTO account_attendance_profiles (account_id,attendance_profile_id,assigned_by)
        SELECT 7,id,10 FROM attendance_profiles ORDER BY id LIMIT 1;`);

    let nextId = 100;
    const seed = async date => {
      const { rows: [record] } = await db.query(`INSERT INTO attendance_records
        (account_id,attendance_date,actual_time_in,recorded_time_in,actual_time_out,recorded_time_out,status)
        VALUES (7,$1,($1::date+TIME '09:20:51') AT TIME ZONE 'Asia/Manila',($1::date+TIME '08:00') AT TIME ZONE 'Asia/Manila',
          ($1::date+TIME '17:20') AT TIME ZONE 'Asia/Manila',($1::date+TIME '17:00') AT TIME ZONE 'Asia/Manila','approved') RETURNING id`, [date]);
      const ids = [nextId++, nextId++, nextId++];
      for (const [index, type, actual, recorded, remark] of [
        [0, 'time_in', '09:20:51', '08:00', null], [1, 'time_out', '17:20', '17:00', null],
        [2, 'time_in', '08:00', '08:00', 'OVERRIDE:EXCUSED:8:Approved schedule'],
      ]) {
        await db.query(`INSERT INTO attendance_logs (id,intern_id,scan_type,scan_time,actual_scan_time,
          recorded_scan_time,attendance_profile_id,attendance_record_id,approval_status,remarks)
          SELECT $1,7,$2,($3::date+$4::time) AT TIME ZONE 'Asia/Manila',
            CASE WHEN $6::text IS NULL THEN ($3::date+$4::time) AT TIME ZONE 'Asia/Manila' ELSE NULL END,
            ($3::date+$5::time) AT TIME ZONE 'Asia/Manila',id,$7,'approved',$6
          FROM attendance_profiles ORDER BY id LIMIT 1`, [ids[index], type, date, actual, recorded, remark, record.id]);
        await db.query('INSERT INTO attendance_photos VALUES ($1,$2)', [ids[index], 'selfie']);
      }
      await db.query(`INSERT INTO dtr_edit_history (attendance_record_id,account_id,field_name,original_value,new_value,modified_by,reason)
        VALUES ($1,7,'Time In','09:20 AM','08:00 AM',10,'Original correction')`, [record.id]);
      return { ids, recordId: record.id };
    };
    const remove = async (date, target = 'all', actor = 10, reason = 'Duplicate attendance verified') => {
      await db.exec('SET ROLE service_role');
      try {
        return (await db.query('SELECT public.delete_admin_dtr_attendance(7,$1,$2,$3,$4) AS result',
          [date, actor, reason, target])).rows[0].result;
      } finally { await db.exec('RESET ROLE'); }
    };
    const snapshot = async () => {
      const result = {};
      for (const table of ['attendance_logs','attendance_records','attendance_photos','dtr_edit_history','attendance_scan_audit']) {
        result[table] = (await db.query(`SELECT * FROM ${table} ORDER BY ${table === 'attendance_photos' ? 'attendance_log_id' : 'id'}`)).rows;
      }
      return result;
    };

    await t.test('full reset removes the selected date, photos and overrides; old audits and edit history survive', async () => {
      const { ids, recordId } = await seed('2026-10-20');
      const { rows: oldAudit } = await db.query('SELECT * FROM attendance_scan_audit ORDER BY id');
      const result = await remove('2026-10-20');
      assert.equal(result.success, true);
      assert.equal(result.deletedLogsCount, 3);
      assert.equal(result.deletedRecord, true);
      assert.equal(result.audit_preserved, true);
      assert.deepEqual(result.deleted_log_ids, ids);
      assert.equal((await db.query('SELECT * FROM attendance_logs WHERE id=ANY($1)', [ids])).rows.length, 0);
      assert.equal((await db.query('SELECT * FROM attendance_photos WHERE attendance_log_id=ANY($1)', [ids])).rows.length, 0);
      assert.equal((await db.query('SELECT * FROM attendance_records WHERE id=$1', [recordId])).rows.length, 0);
      const { rows: audits } = await db.query('SELECT * FROM attendance_scan_audit ORDER BY id');
      assert.deepEqual(audits.slice(0, oldAudit.length), oldAudit);
      const deleted = audits.filter(entry => entry.event_type === 'attendance_deleted');
      assert.equal(deleted.length, 3);
      assert.equal(deleted[0].actual_scan_time.toISOString(), '2026-10-20T01:20:51.000Z');
      assert.equal(deleted[0].approved_by, 10);
      assert.equal(deleted[0].policy_snapshot.deleted_by_role, 'admin');
      const { rows: history } = await db.query('SELECT * FROM dtr_edit_history ORDER BY id');
      assert.equal(history[0].reason, 'Original correction');
      assert.equal(history[0].attendance_record_id, null);
      assert.equal(history.at(-1).reason, 'Duplicate attendance verified');
      assert.equal(history.at(-1).modified_by, 10);
      assert.match(history.at(-1).original_value, /2026-10-20/);
    });

    await t.test('failure on the second deletion restores all scans, photos, records, and audit history', async () => {
      const { ids } = await seed('2026-10-21');
      const before = await snapshot();
      await db.exec(`CREATE FUNCTION fail_dtr_second_audit() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN IF NEW.attendance_log_id=${ids[1]} AND NEW.event_type='attendance_deleted' THEN
          RAISE EXCEPTION 'second audit unavailable'; END IF; RETURN NEW; END $$;
        CREATE TRIGGER fail_dtr_second_audit BEFORE INSERT ON attendance_scan_audit
        FOR EACH ROW EXECUTE FUNCTION fail_dtr_second_audit();`);
      await assert.rejects(remove('2026-10-21'), /second audit unavailable/);
      assert.deepEqual(await snapshot(), before);
      await db.exec('DROP TRIGGER fail_dtr_second_audit ON attendance_scan_audit');
    });

    await t.test('failure to write the requested deletion reason rolls back the whole date', async () => {
      const before = await snapshot();
      await db.exec(`CREATE FUNCTION fail_dtr_history() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN RAISE EXCEPTION 'history unavailable'; END $$;
        CREATE TRIGGER fail_dtr_history BEFORE INSERT ON dtr_edit_history
        FOR EACH ROW EXECUTE FUNCTION fail_dtr_history();`);
      await assert.rejects(remove('2026-10-21'), /history unavailable/);
      assert.deepEqual(await snapshot(), before);
      await db.exec('DROP TRIGGER fail_dtr_history ON dtr_edit_history');
    });

    await t.test('resetting overrides keeps protected scans and their daily mirror', async () => {
      const { ids, recordId } = await seed('2026-10-22');
      const result = await remove('2026-10-22', 'override');
      assert.equal(result.deletedLogsCount, 1);
      assert.equal(result.deletedRecord, false);
      assert.equal((await db.query('SELECT * FROM attendance_logs WHERE id=ANY($1)', [ids.slice(0, 2)])).rows.length, 2);
      assert.equal((await db.query('SELECT * FROM attendance_records WHERE id=$1', [recordId])).rows.length, 1);
    });

    await t.test('unauthorized actors, invalid targets and empty reasons cannot delete anything', async () => {
      const before = await snapshot();
      for (const actor of [7,11,999,null]) await assert.rejects(remove('2026-10-21', 'all', actor), /admin access/i);
      await assert.rejects(remove('2026-10-21', 'invalid'), /target/i);
      await assert.rejects(remove('2026-10-21', 'all', 10, '  '), /reason/i);
      assert.deepEqual(await snapshot(), before);
    });

    await t.test('Superadmin can delete historical protected scans after unassignment without touching other dates', async () => {
      await db.exec('DELETE FROM account_attendance_profiles WHERE account_id=7');
      const beforeOtherDate = (await db.query("SELECT * FROM attendance_logs WHERE scan_time >= '2026-10-22T00:00+08' ORDER BY id")).rows;
      assert.equal((await remove('2026-10-21', 'attendance', 9)).deletedLogsCount, 3);
      assert.deepEqual((await db.query("SELECT * FROM attendance_logs WHERE scan_time >= '2026-10-22T00:00+08' ORDER BY id")).rows, beforeOtherDate);
    });

    await t.test('client roles cannot call the function or erase the retained evidence', async () => {
      const { rows: [grants] } = await db.query(`SELECT
        has_function_privilege('anon','public.delete_admin_dtr_attendance(bigint,date,bigint,text,text)','EXECUTE') AS anon,
        has_function_privilege('authenticated','public.delete_admin_dtr_attendance(bigint,date,bigint,text,text)','EXECUTE') AS authenticated`);
      assert.deepEqual(grants, { anon: false, authenticated: false });
      await assert.rejects(db.exec("UPDATE attendance_scan_audit SET reason='changed'"), /immutable/i);
      await assert.rejects(db.exec('DELETE FROM attendance_scan_audit'), /immutable/i);
      const before = await snapshot();
      await db.exec(migration);
      assert.deepEqual(await snapshot(), before);
    });

    await t.test('daily mirrors without scans can be cleared without losing their old edit history', async () => {
      const { rows: [record] } = await db.query(`INSERT INTO attendance_records (account_id,attendance_date,status)
        VALUES (7,'2026-10-23','approved') RETURNING id`);
      await db.query(`INSERT INTO dtr_edit_history (attendance_record_id,account_id,field_name,modified_by,reason)
        VALUES ($1,7,'Status',10,'Earlier manual correction')`, [record.id]);
      const result = await remove('2026-10-23');
      assert.equal(result.deletedLogsCount, 0);
      assert.equal(result.deletedRecord, true);
      const { rows: [history] } = await db.query("SELECT * FROM dtr_edit_history WHERE reason='Earlier manual correction'");
      assert.equal(history.attendance_record_id, null);
    });

    await t.test('record-linked scans are removed even outside the day range; another intern remains untouched', async () => {
      const { ids, recordId } = await seed('2026-10-24');
      await db.query("UPDATE attendance_logs SET scan_time='2026-10-25T09:00+08' WHERE id=$1", [ids[2]]);
      await db.exec(`INSERT INTO attendance_logs (id,intern_id,scan_type,scan_time,approval_status)
        VALUES (999,8,'time_in','2026-10-24T08:00+08','approved')`);
      const { rows: before } = await db.query('SELECT * FROM attendance_logs WHERE intern_id=8');
      const result = await remove('2026-10-24');
      assert.equal(result.deletedLogsCount, 3);
      assert.equal((await db.query('SELECT * FROM attendance_logs WHERE attendance_record_id=$1', [recordId])).rows.length, 0);
      assert.deepEqual((await db.query('SELECT * FROM attendance_logs WHERE intern_id=8')).rows, before);
    });
  } finally { await db.close(); }
});
